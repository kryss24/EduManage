"""Formatteur JSON pour la journalisation (production uniquement).

Jamais de secret, mot de passe, jeton ou cookie dans les champs supplémentaires
(`extra=...`) passés aux appels de logging : voir `apps.core.audit`.
"""

import json
import logging

# Attributs standards de `logging.LogRecord` : tout le reste provient d'un
# appel `logger.info(..., extra={...})` et doit apparaître dans le JSON.
_STANDARD_ATTRS = {
    "name",
    "msg",
    "args",
    "levelname",
    "levelno",
    "pathname",
    "filename",
    "module",
    "exc_info",
    "exc_text",
    "stack_info",
    "lineno",
    "funcName",
    "created",
    "msecs",
    "relativeCreated",
    "thread",
    "threadName",
    "processName",
    "process",
    "message",
    "asctime",
    "taskName",
}


class JSONFormatter(logging.Formatter):
    def format(self, record):
        payload = {
            "timestamp": self.formatTime(record, "%Y-%m-%dT%H:%M:%S%z"),
            "level": record.levelname,
            "logger": record.name,
            "message": record.getMessage(),
        }
        for key, value in record.__dict__.items():
            if key not in _STANDARD_ATTRS:
                payload[key] = value
        if record.exc_info:
            payload["exc_info"] = self.formatException(record.exc_info)
        return json.dumps(payload, default=str)
